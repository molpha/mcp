/**
 * Writes src/data-catalog.generated.ts from a Molpha Data service's GET /v1/catalog: the templates this
 * release offers as tools (decision D12: tools are generated at build time from a committed snapshot, so
 * a template appears as a tool with an MCP release, not silently).
 *
 *   MOLPHA_DATA_URL=https://data.molpha.io node --import tsx scripts/sync-data-catalog.ts [--check]
 *
 * --check fails when the committed snapshot differs from the service.
 */
import { readFileSync, writeFileSync } from "node:fs";

const url = (process.env.MOLPHA_DATA_URL ?? "https://data.molpha.io").replace(/\/+$/, "");
const out = new URL("../src/data-catalog.generated.ts", import.meta.url);

const res = await fetch(`${url}/v1/catalog`);
if (!res.ok) throw new Error(`GET ${url}/v1/catalog: HTTP ${res.status}`);
const { templates } = (await res.json()) as { templates: Array<Record<string, unknown>> };
// What a tool needs; `chains` is what one deployment serves, so it stays out of the snapshot.
const keep = ["id", "version", "ref", "class", "title", "summary", "kinds", "params", "returns", "caveats", "example", "path"];
const snapshot = templates
  .map((t) => Object.fromEntries(keep.filter((k) => t[k] !== undefined).map((k) => [k, t[k]])))
  .sort((a, b) => String(a.id).localeCompare(String(b.id)));

const text = `// GENERATED by scripts/sync-data-catalog.ts from Molpha Data GET /v1/catalog. Do not edit.
import { type DataTemplate } from "./data.js";

export const DATA_CATALOG: DataTemplate[] = ${JSON.stringify(snapshot, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== text) {
    console.error("src/data-catalog.generated.ts differs from the service's catalog; run scripts/sync-data-catalog.ts");
    process.exit(1);
  }
  console.log(`catalog snapshot matches ${url} (${snapshot.length} templates)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${snapshot.length} templates from ${url}`);
}
